package com.wishconnect.domain.scholarship.entity;

/**
 * 서류를 어떻게 내는가.
 *
 * <p>마감이 "온라인 자정" 인지 "오전 10시 도착분에 한함" 인지에 따라 준비가 완전히 달라진다.
 * 우편이면 며칠 전에 부쳐야 하고, 방문이면 업무시간에 가야 한다.
 *
 * <p>자유 텍스트({@code submissionMethod})와 함께 쓴다. 이 값은 화면 배지·필터용이고,
 * 실제 안내 문구는 텍스트에 있다 — 유형만으로는 "7.30 오전 10시 도착분" 같은 조건을 못 담는다.
 */
public enum SubmissionChannel {

	/** 학교 시스템·구글폼·네이버폼 등 웹 제출. */
	ONLINE,

	EMAIL,

	/** 우편·등기. 도착 기준인지 소인 기준인지가 중요해 텍스트를 함께 봐야 한다. */
	POST,

	/** 직접 방문 제출. */
	VISIT,

	FAX,

	/**
	 * 둘 이상을 함께 요구한다. 실제로 흔하다 —
	 * "시스템에서 신청서 작성 후 증빙서류는 학과 사무실 방문 제출".
	 */
	MIXED
}
