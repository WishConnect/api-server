package com.wishconnect.domain.scholarship.entity;

/**
 * 추천 품질을 재기 위해 남기는 사용자 행동.
 *
 * <p>지금은 추천이 맞는지 <b>알 방법이 없다.</b> 점수식을 바꿔도 좋아졌는지 나빠졌는지 말할 근거가
 * 없어서, 고치는 것마다 취향 논쟁이 된다. 노출 대비 클릭이 오르는지를 보려면 노출부터 남겨야 한다.
 *
 * <p>깔때기 순서대로 쌓인다 — 보여줬다 → 눌렀다 → 담았다 → 쓰기 시작했다. 뒤로 갈수록 사용자가
 * 들이는 노력이 커지므로 신호도 강해진다.
 */
public enum ScholarshipEventType {

	/** 목록·배너에 카드가 보였다. 가장 많이 쌓이고, 나머지 지표의 분모가 된다. */
	IMPRESSION,

	/** 카드를 눌러 상세로 들어갔다. */
	CLICK,

	/** 스크랩했다. */
	SCRAP,

	/** 자기소개서 작성을 시작했다. 가장 강한 신호다. */
	ESSAY_START,

	/**
	 * 공고 원문(지원 페이지)으로 나갔다.
	 *
	 * <p>우리 화면 밖에서 지원하는 장학금이 많아 {@link #ESSAY_START} 만으로는 전환을 못 본다.
	 * 여기까지 왔으면 실제로 지원할 뜻이 있다고 본다.
	 */
	APPLY_CLICK,

	/**
	 * 추천에서 치웠다.
	 *
	 * <p>유일한 <b>부정</b> 신호다. 나머지는 전부 좋아한 흔적만 남아서, 무엇을 위로 올릴지는
	 * 알아도 무엇을 내려야 하는지는 알 수 없었다.
	 */
	DISMISS,

	/** 스크랩을 취소했다. 담았다가 무른 것이므로 {@link #SCRAP} 을 상쇄한다. */
	UNSCRAP
}
