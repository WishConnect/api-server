package com.wishconnect.domain.scholarship.entity;

/**
 * 장학금 모집 상태.
 *
 * <p>신청 시작일·마감일로 계산해 저장한다. 다만 마감일이 없는 공고가 실제로 있어서
 * 날짜만으로는 다 담기지 않는다 — "접수 기간 : 충원 시 마감", "모집 마감", 자동선발처럼
 * 마감일이 존재하지 않는 것이 정상인 공고들이다.
 */
public enum RecruitmentStatus {

	/** 아직 시작 전. 시작일이 미래다. */
	UPCOMING,

	/** 모집 중. 마감일이 있고 아직 지나지 않았다. */
	OPEN,

	/**
	 * 마감일 없이 계속 열려 있다.
	 *
	 * <p>날짜로 판정할 수 없어 자동으로는 닫히지 않는다. 그대로 두면 작년 공고가 영원히
	 * 목록에 남으므로, 관리자 화면에 모아 보여주고 사람이 확인해 닫는다.
	 */
	ALWAYS_OPEN,

	/** 마감됐다. */
	CLOSED
}
