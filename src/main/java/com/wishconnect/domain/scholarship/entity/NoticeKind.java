package com.wishconnect.domain.scholarship.entity;

/**
 * 공지가 어떤 종류인가.
 *
 * <p>장학 게시판에는 모집 공고만 올라오지 않는다. 실측 30건 중 4건이 이런 것이었다 —
 * "장학복지팀 전화번호 변경 안내", "장학금 수혜용 계좌 등록 안내". 장학금으로 목록에 올라와 있었다.
 *
 * <p>연세대는 게시판이 분류를 표기해 줘서 수집 단계에서 걸렀지만, 건국대처럼 표기가 없는 곳은
 * 본문을 읽어야 안다. 그래서 LLM 이 판단한다.
 *
 * <p>부수 효과로 <b>지표가 정확해진다.</b> {@link #RESULT} 는 모집기간이 없는 게 정상인데,
 * 지금은 그것까지 분모에 들어가 "기간 채움률 50%" 처럼 실제보다 나쁘게 나온다.
 */
public enum NoticeKind {

	/** 장학생 모집·선발 공고. 목록에 노출하고 기간·조건을 기대한다. */
	RECRUITMENT,

	/** 선발 결과·지급 일정 안내. 이미 끝난 전형이라 모집기간이 없는 게 정상이다. */
	RESULT,

	/** 장학금 자체가 아닌 안내(연락처 변경, 계좌 등록, 서류 제출 방법). 목록에서 뺀다. */
	GUIDE,

	/**
	 * 장학금과 무관한 공고. 목록에서 뺀다.
	 *
	 * <p>{@link #GUIDE} 와 다르다. GUIDE 는 장학금에 딸린 안내이고, 이건 장학 게시판에
	 * 잘못 올라온 남의 글이다 — 실험 참여자 모집, 직원 채용, 행사 접수.
	 *
	 * <p>성균관대 notice06.do 는 URL 이 장학 카테고리라 수집 단계에서 거를 수 없는데
	 * 학교가 아무거나 올린다. 조건 파싱은 멀쩡히 됐다는 게 함정이다 —
	 * "만 18세 이상, 오른손잡이, VR 멀미가 있는 경우 제외" 를 정확히 뽑아 놓고
	 * 장학금으로 저장했다.
	 */
	NOT_SCHOLARSHIP
}
