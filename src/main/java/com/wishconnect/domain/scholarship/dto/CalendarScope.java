package com.wishconnect.domain.scholarship.dto;

/**
 * 달력에 어떤 장학금을 띄울지.
 *
 * <p>전체를 다 띄우면 달력이 빽빽해져 쓸모가 없다. 피그마 시안의 일정 개수(월 4건 내외)로 보면
 * 사용자와 관련된 것만 띄우는 쪽인데, 기획이 확정되지 않아 세 가지를 모두 지원한다.
 * 프론트가 고르면 되고, 나중에 정해져도 백엔드를 다시 고칠 필요가 없다.
 */
public enum CalendarScope {

	/** 지원 가능한(불충족 조건이 없는) 장학금. 기본값. */
	MATCHED,

	/** 내가 스크랩한 장학금. */
	SCRAPPED,

	/** 모집 중·예정인 전체 장학금. */
	ALL
}
