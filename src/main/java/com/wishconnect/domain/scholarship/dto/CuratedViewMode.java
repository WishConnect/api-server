package com.wishconnect.domain.scholarship.dto;

/**
 * 큐레이팅 화면의 세 가지 상태. 프론트가 어떤 화면을 그릴지 이 값으로 정한다.
 *
 * <p>비어 있는 섹션이 "정말 없는 것"인지 "아직 못 보여주는 것"인지를 배열만 보고는
 * 구분할 수 없어서 상태를 명시적으로 내려준다. {@link #ONBOARDING_REQUIRED} 의 빈 섹션은
 * 데이터가 없는 게 아니라 <b>잠긴</b> 것이고, 화면에서는 흐리게 깔고 그 위에
 * "프로필 업데이트하고 확인하기" 를 얹는다.
 */
public enum CuratedViewMode {

	/**
	 * 비로그인. 추천 없이 지금 지원 가능한 공고를 정렬 기준대로만 보여준다.
	 * featured·교내·조건미충족 섹션이 모두 없고 카드 그리드 하나뿐이다.
	 */
	GUEST,

	/**
	 * 로그인했지만 온보딩 미완료. 마감 임박 배너까지만 보여주고
	 * 교내·조건미충족 섹션은 잠근다. 프로필이 없으면 판정할 근거가 없기 때문이다.
	 */
	ONBOARDING_REQUIRED,

	/** 온보딩 완료. 프로필 기반 추천이 붙는다. */
	PERSONALIZED
}
